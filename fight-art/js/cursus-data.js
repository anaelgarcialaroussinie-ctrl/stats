export const findTrack = (id) => TRACKS.find((t) => t.id === id);
export const allLessons = (track) => track.levels.flatMap((L) => L.lessons.map((x) => ({ ...x, level: L })));
export function findLesson(id) {
  for (const t of TRACKS) for (const L of t.levels) { const x = L.lessons.find((y) => y.id === id); if (x) return { track: t, level: L, lesson: x }; }
  return null;
}
